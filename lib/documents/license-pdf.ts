import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { Brief } from "../licensing/schema";

export type LicensePdfInput = {
  licenseNumber: string;
  publicDisplayLabel: string;
  trackTitle: string;
  sellerId: string;
  audioProvenance: string | null;
  startsAt: Date;
  endsAt: Date;
  purchaseId: string;
  licenseId: string;
  request: Brief;
  amountBaseUnits: string;
  network: string;
  payeeAddress: string | null;
  transactionHash: string | null;
};

export function formatUsdc(baseUnits: string): string {
  const value = BigInt(baseUnits);
  return `${value / 10_000_000n}.${(value % 10_000_000n).toString().padStart(7, "0")}`;
}

function formatDate(value: Date): string {
  return value.toISOString().replace(".000Z", "Z");
}

function formatTerritory(request: Brief): string {
  return request.territory.worldwide ? "Worldwide" : request.territory.countries.join(", ");
}

export async function buildLicensePdf(input: LicensePdfInput): Promise<Uint8Array> {
  const document = await PDFDocument.create();
  document.setTitle(`Grant License ${input.licenseNumber}`);
  document.setAuthor("Grant");
  document.setSubject("Demo music license record");
  document.setCreator("Grant");

  const page = document.addPage([595.28, 841.89]);
  const regular = await document.embedFont(StandardFonts.Helvetica);
  const bold = await document.embedFont(StandardFonts.HelveticaBold);
  const margin = 48;
  const maxWidth = page.getWidth() - margin * 2;
  let cursor = 790;

  function text(value: string, options: { size?: number; bold?: boolean; color?: ReturnType<typeof rgb> } = {}) {
    page.drawText(value, {
      x: margin,
      y: cursor,
      size: options.size ?? 10,
      font: options.bold ? bold : regular,
      color: options.color ?? rgb(0.1, 0.1, 0.1),
    });
    cursor -= (options.size ?? 10) + 6;
  }

  function wrapped(value: string, size = 10, lineHeight = 14) {
    const words = value.split(/\s+/);
    let line = "";
    for (const word of words) {
      const candidate = line ? `${line} ${word}` : word;
      if (regular.widthOfTextAtSize(candidate, size) > maxWidth && line) {
        text(line, { size });
        line = word;
      } else {
        line = candidate;
      }
    }
    if (line) text(line, { size });
    cursor -= lineHeight - size;
  }

  text("Grant Demo Music License", { size: 22, bold: true });
  text(input.licenseNumber, { size: 14, bold: true, color: rgb(0.15, 0.35, 0.65) });
  cursor -= 6;

  text("Licensee", { size: 11, bold: true });
  wrapped(input.publicDisplayLabel);
  text("Track", { size: 11, bold: true });
  wrapped(`${input.trackTitle} (seller: ${input.sellerId})`);
  text("Audio provenance", { size: 11, bold: true });
  wrapped(input.audioProvenance ?? "not recorded", 9, 12);
  text("Term", { size: 11, bold: true });
  wrapped(`${formatDate(input.startsAt)} to ${formatDate(input.endsAt)}`);
  cursor -= 4;

  text("Coverage", { size: 11, bold: true });
  wrapped(`Use: ${input.request.intendedUse}`);
  wrapped(`Platforms: ${input.request.platforms.join(", ")}`);
  wrapped(`Territory: ${formatTerritory(input.request)}`);
  wrapped(`Maximum requested term: ${input.request.termDays} days`);
  wrapped(`Maximum clip duration: ${input.request.clipDurationSeconds} seconds`);
  wrapped(`Client delivery: ${input.request.clientDelivery ? "allowed" : "not allowed"}`);
  wrapped(`Reposting: ${input.request.reposting ? "allowed" : "not allowed"}`);
  wrapped(`Future campaigns: ${input.request.futureCampaigns ? "allowed" : "not allowed"}`);
  cursor -= 4;

  text("Payment and records", { size: 11, bold: true });
  wrapped(`Purchase: ${input.purchaseId}`);
  wrapped(`License: ${input.licenseId}`);
  wrapped(`Network: ${input.network}`);
  wrapped(`Amount: ${formatUsdc(input.amountBaseUnits)} testnet USDC`);
  wrapped(`Payee: ${input.payeeAddress ?? "not configured"}`);
  wrapped(`Settlement transaction: ${input.transactionHash ?? "not recorded"}`);
  cursor -= 10;

  text("Demo disclosure", { size: 11, bold: true, color: rgb(0.55, 0.2, 0.1) });
  wrapped(
    "This is a demo license record generated from fixture terms. The audio is a CC0 demo recording with recorded provenance. Seller authority has not been independently verified. This document is not legal advice, a copyright verification, or proof of music ownership. Testnet settlement proves the payment protocol only.",
    9,
    12,
  );

  page.drawText("Generated by Grant", {
    x: margin,
    y: 30,
    size: 8,
    font: regular,
    color: rgb(0.45, 0.45, 0.45),
  });

  return document.save();
}
